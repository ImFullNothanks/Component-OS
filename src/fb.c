static uint8_t  *fb_addr;
static uint32_t  fb_width;
static uint32_t  fb_height;
static uint32_t  fb_pitch;
static uint8_t   fb_bpp;
static uint32_t  fb_cursor_x = 0;
static uint32_t  fb_cursor_y = 0;

void fb_init(uint64_t addr, uint32_t width, uint32_t height,uint32_t pitch, uint8_t bpp) {
    fb_addr   = (uint8_t *)(uintptr_t)addr;
    fb_width  = width;
    fb_height = height;
    fb_pitch  = pitch;
    fb_bpp    = bpp;
}

uint32_t fb_rgb(uint8_t r, uint8_t g, uint8_t b) {
    return ((uint32_t)r << 16) | ((uint32_t)g << 8) | b;
}

void fb_putpixel(uint32_t x, uint32_t y, uint32_t color) {
    if (x >= fb_width || y >= fb_height) return;
    uint32_t *pixel = (uint32_t *)(fb_addr + y * fb_pitch + x * (fb_bpp / 8));
    *pixel = color;
}

void fb_clear(uint32_t color) {
    fb_cursor_x = 0;
    fb_cursor_y = 0;
    for (uint32_t y = 0; y < fb_height; y++)
        for (uint32_t x = 0; x < fb_width; x++)
            fb_putpixel(x, y, color);
}

void fb_putchar(char c, uint32_t x, uint32_t y, uint32_t fg, uint32_t bg) {
    if ((unsigned char)c >= 128) c = ' ';
    const uint8_t *glyph = font[(unsigned char)c];
    for (int row = 0; row < 8; row++) {
        for (int col = 0; col < 8; col++) {
            uint32_t color = (glyph[row] & (0x80 >> col)) ? fg : bg;
            fb_putpixel(x + col, y + row, color);
        }
    }
}

void fb_putstr(const char *s, uint32_t fg, uint32_t bg) {
    while (*s) {
        if (*s == '\n') {
            fb_cursor_x = 0;
            fb_cursor_y += 8;
        } else if (*s == '\b') {
            if (fb_cursor_x >= 8) {
                fb_cursor_x -= 8;
                fb_putchar(' ', fb_cursor_x, fb_cursor_y, fg, bg);
            }
        } else {
            fb_putchar(*s, fb_cursor_x, fb_cursor_y, fg, bg);
            fb_cursor_x += 8;
            if (fb_cursor_x + 8 > fb_width) {
                fb_cursor_x = 0;
                fb_cursor_y += 8;
            }
        }
        // scroll when we hit the bottom
        if (fb_cursor_y + 8 > fb_height) {
            // memmove the framebuffer up one line
            uint32_t line = 8 * fb_pitch;
            uint8_t *dst = fb_addr;
            uint8_t *src = fb_addr + line;
            uint32_t bytes = (fb_height - 8) * fb_pitch;
            for (uint32_t i = 0; i < bytes; i++)
                dst[i] = src[i];
            // clear last line
            for (uint32_t y = fb_height - 8; y < fb_height; y++)
                for (uint32_t x = 0; x < fb_width; x++)
                    fb_putpixel(x, y, bg);
            fb_cursor_y = fb_height - 8;
        }
        s++;
    }
}
